#!/usr/bin/env python3
# builds src/modules/phone/phone_data.c from libphonenumber's PhoneNumberMetadata.xml
# (apache-2.0, see THIRD_PARTY_NOTICES.md). grab the xml with:
#   git clone --depth 1 https://github.com/google/libphonenumber /tmp/lpn
#   python3 tools/gen_phone.py --xml /tmp/lpn/resources/PhoneNumberMetadata.xml
import argparse, re, sys
import xml.etree.ElementTree as ET

# number types we keep, in the order libphonenumber checks them. name -> xml tag
TYPES = [
    ("fixed line", "fixedLine"),
    ("mobile", "mobile"),
    ("toll free", "tollFree"),
    ("premium rate", "premiumRate"),
    ("shared cost", "sharedCost"),
    ("voip", "voip"),
    ("personal number", "personalNumber"),
    ("pager", "pager"),
    ("uan", "uan"),
    ("voicemail", "voicemail"),
]

def clean(p):
    # libphonenumber strips every bit of whitespace from its patterns
    return re.sub(r"\s+", "", p) if p else p

def pat(el, tag):
    t = el.find(tag)
    if t is None:
        return None
    n = t.find("nationalNumberPattern")
    return clean(n.text) if n is not None and n.text else None

def lengths(el, tag):
    # collect national possibleLengths -> a bitmask (bit L set means length L is valid)
    t = el.find(tag)
    if t is None:
        return 0
    pl = t.find("possibleLengths")
    if pl is None or not pl.get("national"):
        return 0
    mask = 0
    for tok in pl.get("national").split(","):
        tok = tok.strip()
        m = re.fullmatch(r"\[(\d+)-(\d+)\]", tok)
        if m:
            for L in range(int(m.group(1)), int(m.group(2)) + 1):
                mask |= 1 << L
        elif tok.isdigit():
            mask |= 1 << int(tok)
    return mask

def cstr(s):
    if s is None:
        return "NULL"
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + out + '"'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xml", required=True)
    ap.add_argument("--out", default="src/modules/phone/phone_data.c")
    a = ap.parse_args()

    root = ET.parse(a.xml).getroot()
    regions = []
    for terr in root.iter("territory"):
        rid = terr.get("id")
        cc = terr.get("countryCode")
        if not rid or not cc or not cc.isdigit():
            continue
        gd = terr.find("generalDesc")
        general = pat(terr, "generalDesc")
        mask = lengths(terr, "generalDesc")
        if not mask:
            # fall back to the union of every type's lengths
            for _, tag in TYPES:
                mask |= lengths(terr, tag)
        row = {
            "region": rid,
            "cc": int(cc),
            "main": terr.get("mainCountryForCode") == "true",
            "leading": clean(terr.get("leadingDigits")),
            "general": general,
            "mask": mask,
            "types": [(name, pat(terr, tag)) for name, tag in TYPES],
        }
        regions.append(row)

    # single-region country codes come first so the common case is a quick hit; within a
    # shared code the main country goes first
    regions.sort(key=lambda r: (r["cc"], not r["main"], r["region"]))

    out = []
    out.append("// generated by tools/gen_phone.py from libphonenumber metadata. do not edit by hand.")
    out.append('#include "modules/phone/phone.h"\n')
    out.append("// one row per calling-region. patterns are python-subset regex, matched by core/regex.c")
    out.append("const phone_region phone_regions[] = {")
    for r in regions:
        types_c = ", ".join(cstr(p) for _, p in r["types"])
        out.append("    {%s, %d, %s, %s, %s, 0x%xu, {%s}}," % (
            cstr(r["region"]), r["cc"], "true" if r["main"] else "false",
            cstr(r["leading"]), cstr(r["general"]), r["mask"], types_c))
    out.append("};")
    out.append("const size_t phone_regions_n = sizeof phone_regions / sizeof phone_regions[0];")
    out.append("")
    out.append("const char *const phone_type_names[] = {")
    out.append("    " + ", ".join(cstr(name) for name, _ in TYPES) + ",")
    out.append("};")
    out.append("const size_t phone_types_n = %d;" % len(TYPES))
    out.append("")
    text = "\n".join(out) + "\n"
    open(a.out, "w", encoding="utf-8").write(text)
    print("wrote %s: %d regions" % (a.out, len(regions)), file=sys.stderr)

if __name__ == "__main__":
    main()
