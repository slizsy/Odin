#!/usr/bin/env python3
# writes src/modules/email/disposable_data.c from the disposable-email-domains project
# (CC0/MIT, see THIRD_PARTY_NOTICES.md). pass the blocklist file, or let it fetch:
#   python3 tools/gen_disposable.py --file /path/to/disposable_email_blocklist.conf
import argparse, sys, urllib.request

URL = ("https://raw.githubusercontent.com/disposable-email-domains/"
       "disposable-email-domains/main/disposable_email_blocklist.conf")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--file", help="local blocklist file; if omitted, fetch from github")
    ap.add_argument("--out", default="src/modules/email/disposable_data.c")
    a = ap.parse_args()

    if a.file:
        text = open(a.file, "r", encoding="utf-8").read()
    else:
        text = urllib.request.urlopen(URL, timeout=30).read().decode("utf-8")

    domains = set()
    for line in text.splitlines():
        d = line.strip().lower()
        if d and not d.startswith("#"):
            domains.add(d)
    domains = sorted(domains)  # sorted so the C side can binary-search

    out = ["// generated by tools/gen_disposable.py. known throwaway / temp email domains.",
           '#include "modules/email/email.h"', "",
           "// sorted for bsearch in email_cmd.c",
           "const char *const disposable_domains[] = {"]
    line = "    "
    for d in domains:
        piece = '"%s",' % d.replace("\\", "\\\\").replace('"', '\\"')
        if len(line) + len(piece) > 110:
            out.append(line)
            line = "    "
        line += piece + " "
    if line.strip():
        out.append(line.rstrip())
    out.append("};")
    out.append("const size_t disposable_domains_n = sizeof disposable_domains / sizeof disposable_domains[0];")
    open(a.out, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote %s: %d domains" % (a.out, len(domains)), file=sys.stderr)

if __name__ == "__main__":
    main()
