#ifndef ODIN_USAGE_H
#define ODIN_USAGE_H

static const char *usage =
    "usage: odin <command> [flags] [args]\n"
    "       odin                 (no command) interactive mode, type exit to leave\n"
    "\n"
    "commands:\n"
    "  meta <path...>       rip metadata out of files and folders\n"
    "  user <name...>       hunt for a username across a pile of sites\n"
    "  domain <domain...>   dns records, registration (rdap), subdomains (crt.sh)\n"
    "  ip <addr...>         who owns an ip: rdap, geo + asn, reverse dns\n"
    "  email <addr...>      validate an address: syntax, mx, disposable, gravatar\n"
    "  phone <number...>    parse + validate a phone number, offline\n"
    "  upgrade              update odin to the newest release (--check to just look)\n"
    "  help                 this screen\n"
    "  version              print the version\n"
    "\n"
    "meta flags:\n"
    "  -r, --recursive      walk folders all the way down\n"
    "  -f, --findings       only show findings, skip the raw field dump\n"
    "  -x, --exiftool       full dump through exiftool if it's installed\n"
    "  reads jpeg, heic (iphone), avif, png, webp, tiff + camera raws, pdf,\n"
    "  docx/xlsx/pptx, odt/ods/odp, plus xmp hiding in pretty much anything\n"
    "\n"
    "user flags:\n"
    "  -a, --all            also list the sites where it wasn't found\n"
    "  -t, --timeout <sec>  per site timeout (default 15)\n"
    "      --sites <file>   use your own site list (text, odin json, or whatsmyname's\n"
    "                       wmn-data.json) instead of the built in one\n"
    "      --list           print the site list and exit\n"
    "      --selftest       check every site's rule still works\n"
    "\n"
    "domain flags:\n"
    "      --no-subs        skip the crt.sh subdomain lookup (faster)\n"
    "\n"
    "phone flags:\n"
    "  -c, --country <cc>   2-letter country for numbers typed without a + (eg US, GB)\n"
    "\n"
    "everywhere:\n"
    "  -j, --json           json output (pipe it into jq or whatever)\n"
    "  -q, --quiet          skip the banner\n"
    "      --no-color       plain text\n"
    "\n"
    "the domain / ip / email lookups use public records only (dns-over-https, rdap,\n"
    "certificate transparency, gravatar). nothing is sent to the address itself.\n"
    "\n"
    "examples:\n"
    "  odin meta photo.jpg\n"
    "  odin user johndoe jdoe99 -a --json | jq\n"
    "  odin domain example.com\n"
    "  odin ip 8.8.8.8\n"
    "  odin email someone@example.com\n"
    "  odin phone +14155552671\n";

#endif
